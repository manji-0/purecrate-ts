//! Print a `Crate` into kamae-ts files. No I/O.

use std::collections::BTreeMap;

use purecrate_ir::{
    BinOp, Crate, Enum, Expr, Fields, Fn, Item, Lit, Pattern, Struct, Ty, VariantBind,
    VariantFields,
};

const HEADER: &str = "/* generated by purecrate-ts. do not edit. */\n";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct File {
    pub stem: String,
    pub source: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Package {
    pub files: Vec<File>,
}

pub fn emit(krate: &Crate) -> Package {
    let mut buckets: BTreeMap<String, Vec<&Item>> = BTreeMap::new();
    for item in &krate.items {
        buckets.entry(item.file_stem()).or_default().push(item);
    }

    let mut files = vec![
        File {
            stem: "assert-never".to_string(),
            source: assert_never_src(),
        },
        File {
            stem: "result".to_string(),
            source: result_src(),
        },
    ];

    for (stem, items) in &buckets {
        files.push(File {
            stem: stem.clone(),
            source: emit_file(krate, stem, items),
        });
    }

    files.push(File {
        stem: "index".to_string(),
        source: emit_index(krate),
    });

    Package { files }
}

fn assert_never_src() -> String {
    format!(
        "{HEADER}\nexport const assertNever = (x: never): never => {{\n  throw new Error(\"unexpected variant\");\n}};\n"
    )
}

fn result_src() -> String {
    format!(
        "{HEADER}
export type Result<T, E> =
  | Readonly<{{ kind: \"Ok\"; value: T }}>
  | Readonly<{{ kind: \"Err\"; error: E }}>;

export const Result = {{
  ok: <T, E>(value: T): Result<T, E> => ({{ kind: \"Ok\", value }}),
  err: <T, E>(error: E): Result<T, E> => ({{ kind: \"Err\", error }}),
  isOk: <T, E>(r: Result<T, E>): r is Readonly<{{ kind: \"Ok\"; value: T }}> =>
    r.kind === \"Ok\",
  isErr: <T, E>(r: Result<T, E>): r is Readonly<{{ kind: \"Err\"; error: E }}> =>
    r.kind === \"Err\",
}} as const;
"
    )
}

fn emit_index(krate: &Crate) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    out.push_str("export type { Result } from \"./result.ts\";\n");
    out.push_str("export { Result } from \"./result.ts\";\n");
    out.push_str("export { assertNever } from \"./assert-never.ts\";\n");
    for item in krate.exported() {
        match item {
            Item::Fn(f) if f.owner.is_some() => {}
            Item::Fn(f) => {
                let stem = f.name.file_stem();
                out.push_str(&format!(
                    "export {{ {name} }} from \"./{stem}.ts\";\n",
                    name = f.name.as_str(),
                ));
            }
            other => {
                let name = other.name().as_str();
                let stem = other.file_stem();
                out.push_str(&format!(
                    "export type {{ {name} }} from \"./{stem}.ts\";\n"
                ));
                out.push_str(&format!("export {{ {name} }} from \"./{stem}.ts\";\n"));
            }
        }
    }
    out
}

fn emit_file(krate: &Crate, stem: &str, items: &[&Item]) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    let imports = imports_for(krate, stem, items);
    out.push_str(&imports);
    if !imports.is_empty() {
        out.push('\n');
    }
    for item in items {
        match item {
            Item::Enum(en) => out.push_str(&emit_enum(en)),
            Item::Struct(st) => out.push_str(&emit_struct(krate, st)),
            Item::Alias(al) => {
                out.push_str(&format!(
                    "export type {name} = {ty};\n",
                    name = al.name.as_str(),
                    ty = emit_ty(&al.ty)
                ));
            }
            Item::Fn(f) if f.owner.is_none() => out.push_str(&emit_free_fn(f)),
            Item::Fn(_) => {}
        }
    }
    out
}

fn methods_on<'a>(krate: &'a Crate, ty: &str) -> Vec<&'a Fn> {
    krate
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Fn(f) if f.owner.as_ref().map(|n| n.as_str()) == Some(ty) => Some(f),
            _ => None,
        })
        .collect()
}

fn emit_enum(en: &Enum) -> String {
    let name = en.name.as_str();
    let mut out = format!("export type {name} =\n");
    for (i, v) in en.variants.iter().enumerate() {
        let sep = if i + 1 == en.variants.len() {
            ";\n"
        } else {
            "\n"
        };
        out.push_str("  | ");
        out.push_str(&variant_type(v));
        out.push_str(sep);
    }
    out.push('\n');
    out.push_str(&format!("export const {name} = {{\n"));
    for v in &en.variants {
        out.push_str(&format!("  {}: ", v.name.as_str()));
        out.push_str(&variant_ctor(name, v));
        out.push_str(",\n");
    }
    out.push_str("} as const;\n");
    out
}

fn variant_type(v: &purecrate_ir::Variant) -> String {
    let kind = v.name.as_str();
    match &v.fields {
        VariantFields::Unit => format!("Readonly<{{ kind: \"{kind}\" }}>"),
        VariantFields::Tuple(elems) => {
            let inner = elems
                .iter()
                .map(emit_ty)
                .collect::<Vec<_>>()
                .join(", ");
            format!("Readonly<{{ kind: \"{kind}\"; content: readonly [{inner}] }}>")
        }
        VariantFields::Struct(fields) => {
            let mut parts = vec![format!("kind: \"{kind}\"")];
            for f in fields {
                parts.push(format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)));
            }
            format!("Readonly<{{ {} }}>", parts.join("; "))
        }
    }
}

fn variant_ctor(ty: &str, v: &purecrate_ir::Variant) -> String {
    let kind = v.name.as_str();
    match &v.fields {
        VariantFields::Unit => format!("(): {ty} => ({{ kind: \"{kind}\" }})"),
        VariantFields::Tuple(elems) => {
            let params: Vec<String> = elems
                .iter()
                .enumerate()
                .map(|(i, t)| format!("_{i}: {}", emit_ty(t)))
                .collect();
            let args: Vec<String> = (0..elems.len()).map(|i| format!("_{i}")).collect();
            format!(
                "({params}): {ty} => ({{ kind: \"{kind}\", content: [{args}] }})",
                params = params.join(", "),
                args = args.join(", ")
            )
        }
        VariantFields::Struct(fields) => {
            let params: Vec<String> = fields
                .iter()
                .map(|f| format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)))
                .collect();
            let assigns: Vec<String> = fields
                .iter()
                .map(|f| f.name.as_str().to_string())
                .collect();
            format!(
                "({params}): {ty} => ({{ kind: \"{kind}\", {assigns} }})",
                params = params.join(", "),
                assigns = assigns.join(", ")
            )
        }
    }
}

fn emit_struct(krate: &Crate, st: &Struct) -> String {
    let name = st.name.as_str();
    let fields = st
        .fields
        .iter()
        .map(|f| format!("  {}: {};", f.name.as_str(), emit_ty(&f.ty)))
        .collect::<Vec<_>>()
        .join("\n");
    let mut out = format!("export type {name} = Readonly<{{\n{fields}\n}}>;\n\n");
    let params = st
        .fields
        .iter()
        .map(|f| format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let assigns = st
        .fields
        .iter()
        .map(|f| f.name.as_str().to_string())
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(&format!("export const {name} = {{\n"));
    out.push_str(&format!(
        "  of: ({params}): {name} => ({{ {assigns} }}),\n"
    ));
    for m in methods_on(krate, name) {
        out.push_str(&format!(
            "  {n}: {impl},\n",
            n = m.name.as_str(),
            impl = fn_arrow(m)
        ));
    }
    out.push_str("} as const;\n");
    out
}

fn emit_free_fn(f: &Fn) -> String {
    format!(
        "export const {name} = {impl};\n",
        name = f.name.as_str(),
        impl = fn_arrow(f)
    )
}

fn fn_arrow(f: &Fn) -> String {
    let params = f
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name.as_str(), emit_ty(&p.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "({params}): {ret} => {body}",
        ret = emit_ty(&f.ret),
        body = emit_expr(&f.body, 0)
    )
}

fn emit_ty(ty: &Ty) -> String {
    match ty {
        Ty::Prim(p) => match p {
            purecrate_ir::Prim::Bool => "boolean".into(),
            purecrate_ir::Prim::I64 | purecrate_ir::Prim::U64 => "bigint".into(),
            purecrate_ir::Prim::String => "string".into(),
            purecrate_ir::Prim::Unit => "undefined".into(),
            _ => "number".into(),
        },
        Ty::Option(inner) => format!("{} | null", emit_ty(inner)),
        Ty::Result { ok, err } => format!("Result<{}, {}>", emit_ty(ok), emit_ty(err)),
        Ty::Vec(inner) => format!("ReadonlyArray<{}>", emit_ty(inner)),
        Ty::Tuple(elems) => {
            let inner = elems.iter().map(emit_ty).collect::<Vec<_>>().join(", ");
            format!("readonly [{inner}]")
        }
        Ty::Named(n) => n.as_str().to_string(),
        Ty::Never => "never".into(),
    }
}

fn emit_expr(expr: &Expr, indent: usize) -> String {
    match expr {
        Expr::Lit(lit) => emit_lit(lit),
        Expr::Var(n) => n.as_str().to_string(),
        Expr::Field { base, name } => format!("{}.{n}", emit_expr(base, indent), n = name.as_str()),
        Expr::Binary { op, left, right } => format!(
            "{} {} {}",
            emit_expr(left, indent),
            bin_op(*op),
            emit_expr(right, indent)
        ),
        Expr::Unary { op, expr } => {
            let o = match op {
                purecrate_ir::UnOp::Not => "!",
                purecrate_ir::UnOp::Neg => "-",
            };
            format!("{o}{}", emit_expr(expr, indent))
        }
        Expr::Construct { ty, variant, fields } => match variant {
            Some(v) => emit_variant_value(ty.as_str(), v.as_str(), fields),
            None => emit_struct_value(fields),
        },
        Expr::Match { scrutinee, arms } => emit_match(scrutinee, arms, indent),
        Expr::If { cond, then, else_ } => format!(
            "({} ? {} : {})",
            emit_expr(cond, indent),
            emit_expr(then, indent),
            emit_expr(else_, indent)
        ),
        Expr::Call { callee, args } => {
            let c = match callee {
                purecrate_ir::Callee::Fn(n) => n.as_str().to_string(),
                purecrate_ir::Callee::Method { ty, name } => {
                    format!("{}.{}", ty.as_str(), name.as_str())
                }
                purecrate_ir::Callee::Variant { ty, variant } => {
                    format!("{}.{}", ty.as_str(), variant.as_str())
                }
                purecrate_ir::Callee::StructNew(n) => format!("{}.of", n.as_str()),
                purecrate_ir::Callee::ResultOk => "Result.ok".into(),
                purecrate_ir::Callee::ResultErr => "Result.err".into(),
                purecrate_ir::Callee::OptionSome => String::new(),
                purecrate_ir::Callee::OptionNone => "null".into(),
            };
            if matches!(callee, purecrate_ir::Callee::OptionNone) {
                return "null".into();
            }
            if matches!(callee, purecrate_ir::Callee::OptionSome) {
                return emit_expr(&args[0], indent);
            }
            let a = args
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{c}({a})")
        }
        Expr::Tuple(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Expr::Array(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Expr::Let { name, value, then } => format!(
            "(() => {{ const {n} = {v}; return {t}; }})()",
            n = name.as_str(),
            v = emit_expr(value, indent),
            t = emit_expr(then, indent)
        ),
        Expr::Return(e) => format!("(() => {{ return {}; }})()", emit_expr(e, indent)),
        Expr::Unreachable => "assertNever(undefined as never)".into(),
    }
}

fn emit_struct_value(fields: &Fields) -> String {
    match fields {
        Fields::Unit => "{}".into(),
        Fields::Positional(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, 0))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Fields::Named(pairs) => {
            let inner = pairs
                .iter()
                .map(|(n, e)| format!("{k}: {v}", k = n.as_str(), v = emit_expr(e, 0)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ {inner} }}")
        }
    }
}

fn emit_variant_value(_ty: &str, variant: &str, fields: &Fields) -> String {
    match fields {
        Fields::Unit => format!("{{ kind: \"{variant}\" }}"),
        Fields::Positional(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, 0))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ kind: \"{variant}\", content: [{inner}] }}")
        }
        Fields::Named(pairs) => {
            let inner = pairs
                .iter()
                .map(|(n, e)| format!("{k}: {v}", k = n.as_str(), v = emit_expr(e, 0)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ kind: \"{variant}\", {inner} }}")
        }
    }
}

fn emit_match(scrutinee: &Expr, arms: &[purecrate_ir::Arm], indent: usize) -> String {
    let pad = "  ".repeat(indent);
    let pad1 = "  ".repeat(indent + 1);
    let pad2 = "  ".repeat(indent + 2);
    let mut out = format!("(() => {{\n{pad1}switch ({s}.kind) {{\n", s = emit_expr(scrutinee, indent));
    for arm in arms {
        if let Pattern::Variant { variant, bind, .. } = &arm.pattern {
            out.push_str(&format!("{pad1}case \"{v}\":\n", v = variant.as_str()));
            out.push_str(&bind_prelude(bind, &format!("{pad2}")));
            out.push_str(&format!(
                "{pad2}return {body};\n",
                body = emit_expr(&arm.body, indent + 2)
            ));
        }
    }
    out.push_str(&format!("{pad1}default:\n{pad2}return assertNever({s});\n", s = emit_expr(scrutinee, indent)));
    out.push_str(&format!("{pad1}}}\n{pad}}})()"));
    out
}

fn bind_prelude(bind: &VariantBind, pad: &str) -> String {
    match bind {
        VariantBind::Unit => String::new(),
        VariantBind::Tuple(pats) => pats
            .iter()
            .enumerate()
            .filter_map(|(i, p)| match p {
                Pattern::Var(n) => Some(format!("{pad}const {name} = event.content[{i}];\n", name = n.as_str())),
                _ => None,
            })
            .collect(),
        VariantBind::Struct(pairs) => pairs
            .iter()
            .filter_map(|(field, p)| match p {
                Pattern::Var(n) => Some(format!(
                    "{pad}const {name} = event.{f};\n",
                    name = n.as_str(),
                    f = field.as_str()
                )),
                _ => None,
            })
            .collect(),
    }
}

fn emit_lit(lit: &Lit) -> String {
    match lit {
        Lit::Bool(b) => if *b { "true" } else { "false" }.into(),
        Lit::Int(n) => n.to_string(),
        Lit::UInt(n) => n.to_string(),
        Lit::Float(s) => s.clone(),
        Lit::Str(s) => format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")),
        Lit::Unit => "undefined".into(),
        Lit::Null => "null".into(),
    }
}

fn bin_op(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Rem => "%",
        BinOp::Eq => "===",
        BinOp::Ne => "!==",
        BinOp::Lt => "<",
        BinOp::Le => "<=",
        BinOp::Gt => ">",
        BinOp::Ge => ">=",
        BinOp::And => "&&",
        BinOp::Or => "||",
    }
}

fn imports_for(krate: &Crate, stem: &str, items: &[&Item]) -> String {
    let mut need_never = false;
    let mut need_result = false;
    let mut types: Vec<String> = Vec::new();

    for item in items {
        if let Item::Fn(f) = item {
            if contains_match(&f.body) {
                need_never = true;
            }
            if matches!(f.ret, Ty::Result { .. })
                || f.params.iter().any(|p| matches!(p.ty, Ty::Result { .. }))
            {
                need_result = true;
            }
            for p in &f.params {
                if let Ty::Named(n) = &p.ty {
                    let other = n.file_stem();
                    if other != stem && !types.contains(&n.as_str().to_string()) {
                        types.push(n.as_str().to_string());
                    }
                }
            }
            if let Ty::Named(n) = &f.ret {
                let other = n.file_stem();
                if other != stem && !types.contains(&n.as_str().to_string()) {
                    types.push(n.as_str().to_string());
                }
            }
        }
    }
    let _ = krate;
    let mut out = String::new();
    if need_never {
        out.push_str("import { assertNever } from \"./assert-never.ts\";\n");
    }
    if need_result {
        out.push_str("import type { Result } from \"./result.ts\";\n");
        out.push_str("import { Result } from \"./result.ts\";\n");
    }
    for t in types {
        let s = purecrate_ir::Name::new(t.clone()).file_stem();
        out.push_str(&format!("import type {{ {t} }} from \"./{s}.ts\";\n"));
    }
    out
}

fn contains_match(expr: &Expr) -> bool {
    match expr {
        Expr::Match { .. } => true,
        Expr::Let { value, then, .. } => contains_match(value) || contains_match(then),
        Expr::If { cond, then, else_ } => {
            contains_match(cond) || contains_match(then) || contains_match(else_)
        }
        Expr::Call { args, .. } => args.iter().any(contains_match),
        Expr::Construct { fields, .. } => match fields {
            Fields::Positional(xs) => xs.iter().any(contains_match),
            Fields::Named(xs) => xs.iter().any(|(_, e)| contains_match(e)),
            Fields::Unit => false,
        },
        Expr::Field { base, .. } | Expr::Unary { expr: base, .. } | Expr::Return(base) => {
            contains_match(base)
        }
        Expr::Binary { left, right, .. } => contains_match(left) || contains_match(right),
        Expr::Tuple(xs) | Expr::Array(xs) => xs.iter().any(contains_match),
        Expr::Lit(_) | Expr::Var(_) | Expr::Unreachable => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use purecrate_ir::counter_example;

    fn file<'a>(pkg: &'a Package, stem: &str) -> &'a str {
        &pkg.files
            .iter()
            .find(|f| f.stem == stem)
            .unwrap_or_else(|| panic!("missing {stem}"))
            .source
    }

    #[test]
    fn counter_kamae_shape() {
        let pkg = emit(&counter_example());
        let stems: Vec<&str> = pkg.files.iter().map(|f| f.stem.as_str()).collect();
        assert!(stems.contains(&"event"));
        assert!(stems.contains(&"state"));
        assert!(stems.contains(&"step"));

        let event = file(&pkg, "event");
        assert!(event.contains("kind: \"Inc\""));
        assert!(event.contains("export const Event = {"));
        assert!(!event.contains("tag:"));

        let state = file(&pkg, "state");
        assert!(state.contains("export type State = Readonly<{"));
        assert!(state.contains("of: (n: number): State =>"));

        let step = file(&pkg, "step");
        assert!(step.contains("export const step ="));
        assert!(step.contains("switch (event.kind)"));
        assert!(step.contains("assertNever(event)"));
        assert!(step.contains("import type { Event }"));
        assert!(step.contains("import type { State }"));
    }
}
