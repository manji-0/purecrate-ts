//! Print a `Crate` into kamae-ts files. No I/O.

use std::collections::{BTreeMap, BTreeSet};

use purecrate_ir::{
    BinOp, Callee, ClosureParam, Crate, Enum, Expr, Fields, FloatTy, Fn, IntTy, Item, Lit, Name, Pattern, TryOn,
    Struct, Ty, VariantBind, VariantFields, NEWTYPE_FIELD,
};

const HEADER: &str = "/* generated by purecrate-ts. do not edit. */\n";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct File {
    pub stem: String,
    pub source: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Package {
    pub files: Vec<File>,
}

pub fn emit(krate: &Crate) -> Package {
    let mut buckets: BTreeMap<String, Vec<&Item>> = BTreeMap::new();
    for item in &krate.items {
        buckets.entry(item.file_stem()).or_default().push(item);
    }

    let mut files = vec![
        File {
            stem: "assert-never".to_string(),
            source: assert_never_src(),
        },
        File {
            stem: "int".to_string(),
            source: int_src(),
        },
        File {
            stem: "result".to_string(),
            source: result_src(),
        },
    ];

    for (stem, items) in &buckets {
        files.push(File {
            stem: stem.clone(),
            source: emit_file(krate, stem, items),
        });
    }

    files.push(File {
        stem: "index".to_string(),
        source: emit_index(krate),
    });

    Package { files }
}

fn assert_never_src() -> String {
    format!(
        "{HEADER}\nexport const assertNever = (x: never): never => {{\n  throw new Error(\"unexpected variant\");\n}};\n"
    )
}

/// Integer arithmetic as a Rust debug build does it. `number` widths stay
/// exact because every in-range result is below 2^53, and rounding cannot move
/// an out-of-range product back inside the bounds. `+ 0` turns `-0` into `0`.
fn int_src() -> String {
    let small = IntTy::ALL
        .into_iter()
        .filter(|t| !t.is_big())
        .map(|t| {
            let (lo, hi) = t.bounds();
            format!("  {}: small({lo}, {hi}),\n", t.as_str())
        })
        .collect::<String>();
    let big = IntTy::ALL
        .into_iter()
        .filter(|t| t.is_big())
        .map(|t| {
            let (lo, hi) = t.bounds();
            format!("  {}: big({lo}n, {hi}n),\n", t.as_str())
        })
        .collect::<String>();
    format!(
        "{HEADER}
const panic = (what: string): never => {{
  throw new Error(`attempt to ${{what}}`);
}};

const small = (min: number, max: number) => {{
  const fit = (n: number, what: string): number =>
    n < min || n > max ? panic(`${{what}} with overflow`) : n + 0;
  return {{
    add: (a: number, b: number): number => fit(a + b, \"add\"),
    sub: (a: number, b: number): number => fit(a - b, \"subtract\"),
    mul: (a: number, b: number): number => fit(a * b, \"multiply\"),
    div: (a: number, b: number): number =>
      b === 0 ? panic(\"divide by zero\") : fit(Math.trunc(a / b), \"divide\"),
    rem: (a: number, b: number): number =>
      b === 0
        ? panic(\"calculate the remainder with a divisor of zero\")
        : (fit(Math.trunc(a / b), \"calculate the remainder\"), (a % b) + 0),
    neg: (a: number): number => fit(-a, \"negate\"),
  }} as const;
}};

const big = (min: bigint, max: bigint) => {{
  const fit = (n: bigint, what: string): bigint =>
    n < min || n > max ? panic(`${{what}} with overflow`) : n;
  return {{
    add: (a: bigint, b: bigint): bigint => fit(a + b, \"add\"),
    sub: (a: bigint, b: bigint): bigint => fit(a - b, \"subtract\"),
    mul: (a: bigint, b: bigint): bigint => fit(a * b, \"multiply\"),
    div: (a: bigint, b: bigint): bigint =>
      b === 0n ? panic(\"divide by zero\") : fit(a / b, \"divide\"),
    rem: (a: bigint, b: bigint): bigint =>
      b === 0n
        ? panic(\"calculate the remainder with a divisor of zero\")
        : (fit(a / b, \"calculate the remainder\"), a % b),
    neg: (a: bigint): bigint => fit(-a, \"negate\"),
  }} as const;
}};

export const Int = {{
{small}{big}}} as const;
"
    )
}

fn result_src() -> String {
    format!(
        "{HEADER}
export type Result<T, E> =
  | Readonly<{{ kind: \"Ok\"; value: T }}>
  | Readonly<{{ kind: \"Err\"; error: E }}>;

export const Result = {{
  ok: <T, E>(value: T): Result<T, E> => ({{ kind: \"Ok\", value }}),
  err: <T, E>(error: E): Result<T, E> => ({{ kind: \"Err\", error }}),
  isOk: <T, E>(r: Result<T, E>): r is Readonly<{{ kind: \"Ok\"; value: T }}> =>
    r.kind === \"Ok\",
  isErr: <T, E>(r: Result<T, E>): r is Readonly<{{ kind: \"Err\"; error: E }}> =>
    r.kind === \"Err\",
}} as const;
"
    )
}

fn emit_index(krate: &Crate) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    // A single value export carries both the companion and its same-named type.
    out.push_str("export { Result } from \"./result.ts\";\n");
    out.push_str("export { assertNever } from \"./assert-never.ts\";\n");
    for item in krate.exported() {
        match item {
            Item::Fn(f) if f.owner.is_some() => {}
            Item::Alias(al) => {
                out.push_str(&format!(
                    "export type {{ {name} }} from \"./{stem}.ts\";\n",
                    name = al.name.as_str(),
                    stem = item.file_stem(),
                ));
            }
            other => {
                out.push_str(&format!(
                    "export {{ {name} }} from \"./{stem}.ts\";\n",
                    name = other.name().as_str(),
                    stem = other.file_stem(),
                ));
            }
        }
    }
    out
}

fn emit_file(krate: &Crate, stem: &str, items: &[&Item]) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    let imports = imports_for(krate, stem, items);
    out.push_str(&imports);
    if !imports.is_empty() {
        out.push('\n');
    }
    for item in items {
        match item {
            Item::Enum(en) => out.push_str(&emit_enum(krate, en)),
            Item::Struct(st) => out.push_str(&emit_struct(krate, st)),
            Item::Alias(al) => {
                out.push_str(&format!(
                    "export type {name} = {ty};\n",
                    name = al.name.as_str(),
                    ty = emit_ty(&al.ty)
                ));
            }
            Item::Fn(f) if f.owner.is_none() => out.push_str(&emit_free_fn(f)),
            Item::Fn(_) => {}
        }
    }
    out
}

fn methods_on<'a>(krate: &'a Crate, ty: &str) -> Vec<&'a Fn> {
    krate
        .items
        .iter()
        .filter_map(|item| match item {
            Item::Fn(f) if f.owner.as_ref().map(|n| n.as_str()) == Some(ty) => Some(f),
            _ => None,
        })
        .collect()
}

fn emit_enum(krate: &Crate, en: &Enum) -> String {
    let name = en.name.as_str();
    let mut out = format!("export type {name} =\n");
    for (i, v) in en.variants.iter().enumerate() {
        let sep = if i + 1 == en.variants.len() {
            ";\n"
        } else {
            "\n"
        };
        out.push_str("  | ");
        out.push_str(&variant_type(v));
        out.push_str(sep);
    }
    out.push('\n');
    out.push_str(&format!("export const {name} = {{\n"));
    for v in &en.variants {
        out.push_str(&format!("  {}: ", v.name.as_str()));
        out.push_str(&variant_ctor(name, v));
        out.push_str(",\n");
    }
    for m in methods_on(krate, name) {
        out.push_str(&format!(
            "  {n}: {impl},\n",
            n = m.name.as_str(),
            impl = fn_arrow(m, 1)
        ));
    }
    out.push_str("} as const;\n");
    out
}

fn variant_type(v: &purecrate_ir::Variant) -> String {
    let kind = v.name.as_str();
    match &v.fields {
        VariantFields::Unit => format!("Readonly<{{ kind: \"{kind}\" }}>"),
        VariantFields::Tuple(elems) => {
            let inner = elems
                .iter()
                .map(emit_ty)
                .collect::<Vec<_>>()
                .join(", ");
            format!("Readonly<{{ kind: \"{kind}\"; content: readonly [{inner}] }}>")
        }
        VariantFields::Struct(fields) => {
            let mut parts = vec![format!("kind: \"{kind}\"")];
            for f in fields {
                parts.push(format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)));
            }
            format!("Readonly<{{ {} }}>", parts.join("; "))
        }
    }
}

fn variant_ctor(ty: &str, v: &purecrate_ir::Variant) -> String {
    let kind = v.name.as_str();
    match &v.fields {
        VariantFields::Unit => format!("(): {ty} => ({{ kind: \"{kind}\" }})"),
        VariantFields::Tuple(elems) => {
            let params: Vec<String> = elems
                .iter()
                .enumerate()
                .map(|(i, t)| format!("_{i}: {}", emit_ty(t)))
                .collect();
            let args: Vec<String> = (0..elems.len()).map(|i| format!("_{i}")).collect();
            format!(
                "({params}): {ty} => ({{ kind: \"{kind}\", content: [{args}] }})",
                params = params.join(", "),
                args = args.join(", ")
            )
        }
        VariantFields::Struct(fields) => {
            let params: Vec<String> = fields
                .iter()
                .map(|f| format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)))
                .collect();
            let assigns: Vec<String> = fields
                .iter()
                .map(|f| f.name.as_str().to_string())
                .collect();
            format!(
                "({params}): {ty} => ({{ kind: \"{kind}\", {assigns} }})",
                params = params.join(", "),
                assigns = assigns.join(", ")
            )
        }
    }
}

fn emit_struct(krate: &Crate, st: &Struct) -> String {
    let name = st.name.as_str();
    if let Some(inner) = st.newtype_inner() {
        return emit_newtype(krate, name, inner);
    }
    let fields = st
        .fields
        .iter()
        .map(|f| format!("  {}: {};", f.name.as_str(), emit_ty(&f.ty)))
        .collect::<Vec<_>>()
        .join("\n");
    let mut out = format!("export type {name} = Readonly<{{\n{fields}\n}}>;\n\n");
    let params = st
        .fields
        .iter()
        .map(|f| format!("{}: {}", f.name.as_str(), emit_ty(&f.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let assigns = st
        .fields
        .iter()
        .map(|f| f.name.as_str().to_string())
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(&format!("export const {name} = {{\n"));
    out.push_str(&format!(
        "  of: ({params}): {name} => ({{ {assigns} }}),\n"
    ));
    for m in methods_on(krate, name) {
        out.push_str(&format!(
            "  {n}: {impl},\n",
            n = m.name.as_str(),
            impl = fn_arrow(m, 1)
        ));
    }
    out.push_str("} as const;\n");
    out
}

/// A newtype is its inner value at runtime (as in serde's JSON), branded so
/// that `Id` and the bare inner type do not mix. A `unique symbol` key keeps
/// nested brands from colliding.
fn emit_newtype(krate: &Crate, name: &str, inner: &Ty) -> String {
    let inner = emit_ty(inner);
    let mut out = format!(
        "declare const {name}Brand: unique symbol;\n\
         export type {name} = {inner} & {{ readonly [{name}Brand]: true }};\n\n"
    );
    out.push_str(&format!("export const {name} = {{\n"));
    out.push_str(&format!("  of: (value: {inner}): {name} => value as {name},\n"));
    for m in methods_on(krate, name) {
        out.push_str(&format!(
            "  {n}: {impl},\n",
            n = m.name.as_str(),
            impl = fn_arrow(m, 1)
        ));
    }
    out.push_str("} as const;\n");
    out
}

fn emit_free_fn(f: &Fn) -> String {
    format!(
        "export const {name} = {impl};\n",
        name = f.name.as_str(),
        impl = fn_arrow(f, 0)
    )
}

/// `indent` is the nesting level of the line the arrow starts on.
fn fn_arrow(f: &Fn, indent: usize) -> String {
    let params = f
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name.as_str(), emit_ty(&p.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    arrow(&params, &emit_ty(&f.ret), &f.body, indent)
}

fn closure_arrow(params: &[ClosureParam], ret: Option<&Ty>, body: &Expr, indent: usize) -> String {
    let typed = |name: &Name, ty: Option<&Ty>| match ty {
        Some(t) => format!("{}: {}", name.as_str(), emit_ty(t)),
        None => name.as_str().to_string(),
    };
    let params = params.iter().map(|p| typed(&p.name, p.ty.as_ref())).collect::<Vec<_>>().join(", ");
    match ret {
        Some(r) => arrow(&params, &emit_ty(r), body, indent),
        None => format!("({params}) => {}", arrow_expr(body, indent)),
    }
}

fn arrow(params: &str, ret: &str, body: &Expr, indent: usize) -> String {
    if body.needs_statements() {
        let mut out = String::new();
        emit_stmts(body, indent + 1, Sink::Return, &mut out);
        format!("({params}): {ret} => {{\n{out}{pad}}}", pad = "  ".repeat(indent))
    } else {
        format!("({params}): {ret} => {}", arrow_expr(body, indent))
    }
}

/// An arrow body starting with `{` would parse as a block.
fn arrow_expr(expr: &Expr, indent: usize) -> String {
    let s = emit_expr(expr, indent);
    if s.starts_with('{') {
        format!("({s})")
    } else {
        s
    }
}

/// Where the value of a statement-lowered expression goes.
#[derive(Clone, Copy)]
enum Sink<'a> {
    Return,
    /// A `let` declared without an initializer, or a `let mut` binding.
    Assign(&'a str),
    /// The value is dropped: the expression is a Rust statement.
    Effect,
}

impl Sink<'_> {
    fn finish(self, value: &str, pad: &str, out: &mut String) {
        match self {
            Sink::Return => out.push_str(&format!("{pad}return {value};\n")),
            Sink::Assign(target) => out.push_str(&format!("{pad}{target} = {value};\n")),
            // A variable or `()` has no effect; anything else may panic.
            Sink::Effect if value == "undefined" || is_ident(value) => {}
            Sink::Effect if value.starts_with('{') => out.push_str(&format!("{pad}({value});\n")),
            Sink::Effect => out.push_str(&format!("{pad}{value};\n")),
        }
    }

    /// Unique per nesting level, so an inner temporary never shadows one an
    /// arm prelude still reads.
    fn temp(self, indent: usize) -> String {
        match self {
            Sink::Return | Sink::Effect => format!("$m{indent}"),
            Sink::Assign(target) => format!("$m{indent}_{target}"),
        }
    }
}

/// Lower an expression into statements that hand its value to `sink`.
fn emit_stmts(expr: &Expr, indent: usize, sink: Sink, out: &mut String) {
    let pad = "  ".repeat(indent);
    match expr {
        Expr::Let {
            name,
            mutable,
            ty,
            value,
            then,
        } => {
            emit_let(name.as_str(), *mutable, ty.as_ref(), value, indent, out);
            emit_stmts(then, indent, sink, out);
        }
        Expr::If { cond, then, else_ } if expr.needs_statements() => {
            out.push_str(&format!("{pad}if ({}) {{\n", emit_expr(cond, indent)));
            emit_stmts(then, indent + 1, sink, out);
            if !(matches!(sink, Sink::Effect) && **else_ == Expr::Lit(Lit::Unit)) {
                out.push_str(&format!("{pad}}} else {{\n"));
                emit_stmts(else_, indent + 1, sink, out);
            }
            out.push_str(&format!("{pad}}}\n"));
        }
        Expr::Assign { name, value } => {
            if value.needs_statements() {
                emit_stmts(value, indent, Sink::Assign(name.as_str()), out);
            } else {
                out.push_str(&format!("{pad}{} = {};\n", name.as_str(), emit_expr(value, indent)));
            }
            sink.finish("undefined", &pad, out);
        }
        Expr::Seq { first, then } => {
            emit_stmts(first, indent, Sink::Effect, out);
            let dead = matches!(**first, Expr::Return(_)) && **then == Expr::Lit(Lit::Unit);
            if !dead {
                emit_stmts(then, indent, sink, out);
            }
        }
        Expr::Match { scrutinee, arms } => emit_switch(scrutinee, arms, indent, sink, out),
        Expr::Return(value) => out.push_str(&format!("{pad}return {};\n", emit_expr(value, indent))),
        Expr::Try { .. } => {
            let tmp = format!("$t{indent}");
            emit_let(&tmp, false, None, expr, indent, out);
            sink.finish(&tmp, &pad, out);
        }
        other => sink.finish(&emit_expr(other, indent), &pad, out),
    }
}

fn emit_let(name: &str, mutable: bool, ty: Option<&Ty>, value: &Expr, indent: usize, out: &mut String) {
    let pad = "  ".repeat(indent);
    let keyword = if mutable { "let" } else { "const" };
    let annotation = ty.map(|t| format!(": {}", emit_ty(t))).unwrap_or_default();
    match value {
        Expr::Try { expr, on } => {
            let tmp = format!("${name}");
            out.push_str(&format!("{pad}const {tmp} = {};\n", emit_expr(expr, indent)));
            match on {
                Some(TryOn::Option) => out.push_str(&format!(
                    "{pad}if ({tmp} === null) return null;\n{pad}{keyword} {name}{annotation} = {tmp};\n"
                )),
                Some(TryOn::Result) | None => out.push_str(&format!(
                    "{pad}if ({tmp}.kind === \"Err\") return {tmp};\n{pad}{keyword} {name}{annotation} = {tmp}.value;\n"
                )),
            }
        }
        v if v.needs_statements() => {
            out.push_str(&format!("{pad}let {name}{annotation};\n"));
            if matches!(v, Expr::Let { .. } | Expr::Seq { .. }) {
                // A Rust block: its bindings end with it.
                out.push_str(&format!("{pad}{{\n"));
                emit_stmts(v, indent + 1, Sink::Assign(name), out);
                out.push_str(&format!("{pad}}}\n"));
            } else {
                emit_stmts(v, indent, Sink::Assign(name), out);
            }
        }
        v => out.push_str(&format!(
            "{pad}{keyword} {name}{annotation} = {};\n",
            emit_expr(v, indent)
        )),
    }
}

/// `x`, `x.a.b`: references TS can narrow through `switch (x.kind)`.
fn is_place(expr: &Expr) -> bool {
    match expr {
        Expr::Var(_) => true,
        Expr::Field { base, .. } => is_place(base),
        _ => false,
    }
}

/// Without an annotation a variant literal widens to `{ kind: string }`.
fn scrutinee_ty(arms: &[purecrate_ir::Arm]) -> Option<&purecrate_ir::Name> {
    arms.iter().find_map(|arm| match &arm.pattern {
        Pattern::Variant { ty, .. } => Some(ty),
        _ => None,
    })
}

fn declares_at_top(expr: &Expr) -> bool {
    match expr {
        Expr::Let { .. } | Expr::Try { .. } | Expr::Seq { .. } | Expr::Assign { .. } => true,
        Expr::Match { scrutinee, .. } => !is_place(scrutinee),
        _ => false,
    }
}

fn emit_switch(
    scrutinee: &Expr,
    arms: &[purecrate_ir::Arm],
    indent: usize,
    sink: Sink,
    out: &mut String,
) {
    // Statements after this one may hold another `match` at the same depth;
    // a block keeps the two temporaries apart.
    if !is_place(scrutinee) && !matches!(sink, Sink::Return) {
        let pad = "  ".repeat(indent);
        out.push_str(&format!("{pad}{{\n"));
        emit_switch_in(scrutinee, arms, indent + 1, sink, out);
        out.push_str(&format!("{pad}}}\n"));
    } else {
        emit_switch_in(scrutinee, arms, indent, sink, out);
    }
}

fn emit_switch_in(
    scrutinee: &Expr,
    arms: &[purecrate_ir::Arm],
    indent: usize,
    sink: Sink,
    out: &mut String,
) {
    let pad = "  ".repeat(indent);
    let pad1 = "  ".repeat(indent + 1);
    let subject = if is_place(scrutinee) {
        emit_expr(scrutinee, indent)
    } else {
        let tmp = sink.temp(indent);
        let value = emit_expr(scrutinee, indent);
        // An annotated literal initializer narrows the union and makes the
        // other cases unreachable; a cast keeps the full union.
        let decl = match (scrutinee_ty(arms), scrutinee) {
            (Some(ty), Expr::Construct { .. }) => format!("{tmp} = {value} as {}", ty.as_str()),
            (Some(ty), _) => format!("{tmp}: {} = {value}", ty.as_str()),
            (None, _) => format!("{tmp} = {value}"),
        };
        out.push_str(&format!("{pad}const {decl};\n"));
        tmp
    };
    if let [a, b] = arms {
        if let (Some(test), Some(_)) = (two_way_test(&a.pattern, &subject), two_way_test(&b.pattern, &subject)) {
            let pad2 = "  ".repeat(indent + 1);
            out.push_str(&format!("{pad}if ({test}) {{\n"));
            out.push_str(&two_way_prelude(&a.pattern, &subject, &pad2));
            emit_stmts(&a.body, indent + 1, sink, out);
            if !(matches!(sink, Sink::Effect) && b.body == Expr::Lit(Lit::Unit)) {
                out.push_str(&format!("{pad}}} else {{\n"));
                out.push_str(&two_way_prelude(&b.pattern, &subject, &pad2));
                emit_stmts(&b.body, indent + 1, sink, out);
            }
            out.push_str(&format!("{pad}}}\n"));
            return;
        }
    }
    out.push_str(&format!("{pad}switch ({subject}.kind) {{\n"));
    for arm in arms {
        if let Pattern::Variant { variant, bind, .. } = &arm.pattern {
            out.push_str(&format!("{pad1}case \"{v}\":", v = variant.as_str()));
            let prelude = bind_prelude(bind, &subject, &"  ".repeat(indent + 2));
            let braced = !prelude.is_empty() || declares_at_top(&arm.body);
            out.push_str(if braced { " {\n" } else { "\n" });
            out.push_str(&prelude);
            emit_stmts(&arm.body, indent + 2, sink, out);
            if !matches!(sink, Sink::Return) && !matches!(arm.body, Expr::Return(_)) {
                out.push_str(&format!("{pad1}  break;\n"));
            }
            if braced {
                out.push_str(&format!("{pad1}}}\n"));
            }
        }
    }
    out.push_str(&format!(
        "{pad1}default:\n{pad1}  return assertNever({subject});\n{pad}}}\n"
    ));
}

/// `Option` is `T | null` and `Result` is `kind`-tagged, so both narrow
/// with a single test.
fn two_way_test(pattern: &Pattern, subject: &str) -> Option<String> {
    match pattern {
        Pattern::OptionSome(_) => Some(format!("{subject} !== null")),
        Pattern::OptionNone => Some(format!("{subject} === null")),
        Pattern::ResultOk(_) => Some(format!("{subject}.kind === \"Ok\"")),
        Pattern::ResultErr(_) => Some(format!("{subject}.kind === \"Err\"")),
        _ => None,
    }
}

fn two_way_prelude(pattern: &Pattern, subject: &str, pad: &str) -> String {
    let (inner, read) = match pattern {
        Pattern::OptionSome(p) => (p, subject.to_string()),
        Pattern::ResultOk(p) => (p, format!("{subject}.value")),
        Pattern::ResultErr(p) => (p, format!("{subject}.error")),
        _ => return String::new(),
    };
    match &**inner {
        Pattern::Var(n) => format!("{pad}const {} = {read};\n", n.as_str()),
        _ => String::new(),
    }
}

fn emit_ty(ty: &Ty) -> String {
    match ty {
        Ty::Prim(p) => match p {
            purecrate_ir::Prim::Bool => "boolean".into(),
            purecrate_ir::Prim::I64 | purecrate_ir::Prim::U64 => "bigint".into(),
            purecrate_ir::Prim::String => "string".into(),
            purecrate_ir::Prim::Unit => "undefined".into(),
            _ => "number".into(),
        },
        Ty::Option(inner) => format!("{} | null", emit_ty(inner)),
        Ty::Result { ok, err } => format!("Result<{}, {}>", emit_ty(ok), emit_ty(err)),
        Ty::Vec(inner) => format!("ReadonlyArray<{}>", emit_ty(inner)),
        Ty::Tuple(elems) => {
            let inner = elems.iter().map(emit_ty).collect::<Vec<_>>().join(", ");
            format!("readonly [{inner}]")
        }
        Ty::Named(n) => n.as_str().to_string(),
        Ty::Fn { params, ret } => {
            let params = params
                .iter()
                .enumerate()
                .map(|(i, t)| format!("_{i}: {}", emit_ty(t)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("(({params}) => {})", emit_ty(ret))
        }
        Ty::Never => "never".into(),
    }
}

fn emit_expr(expr: &Expr, indent: usize) -> String {
    match expr {
        Expr::Lit(lit) => emit_lit(lit),
        Expr::Var(n) => n.as_str().to_string(),
        Expr::Field { base, name } if name.as_str() == NEWTYPE_FIELD => emit_expr(base, indent),
        Expr::Field { base, name } => format!("{}.{n}", emit_expr(base, indent), n = name.as_str()),
        Expr::Binary { op, left, right } => format!(
            "{} {} {}",
            operand(left, indent),
            bin_op(*op),
            operand(right, indent)
        ),
        Expr::Unary { op, expr } => {
            let o = match op {
                purecrate_ir::UnOp::Not => "!",
                purecrate_ir::UnOp::Neg => "-",
            };
            let inner = operand(expr, indent);
            if inner.starts_with(o) {
                format!("{o}({inner})")
            } else {
                format!("{o}{inner}")
            }
        }
        Expr::Closure { params, ret, body } => format!("({})", closure_arrow(params, ret.as_ref(), body, indent)),
        Expr::MethodCall { name, .. } => {
            unreachable!("`.{}()` reaches emit unresolved; emit takes `check::accept` output", name.as_str())
        }
        Expr::Construct { ty, variant, fields, base } => match (variant, base) {
            (Some(v), None) => emit_variant_value(ty.as_str(), v.as_str(), fields),
            (None, None) => emit_struct_value(fields),
            (None, Some(base)) => emit_struct_update(fields, base),
            (Some(_), Some(_)) => unreachable!("enum variants have no struct update"),
        },
        Expr::Match { .. } | Expr::Let { .. } => emit_iife(expr, indent),
        Expr::If { .. } if expr.needs_statements() => emit_iife(expr, indent),
        Expr::Try { .. } | Expr::Seq { .. } | Expr::Assign { .. } => emit_iife(expr, indent),
        Expr::If { cond, then, else_ } => format!(
            "({} ? {} : {})",
            emit_expr(cond, indent),
            emit_expr(then, indent),
            emit_expr(else_, indent)
        ),
        Expr::Call { callee, args } => {
            let c = match callee {
                purecrate_ir::Callee::Fn(n) | purecrate_ir::Callee::Local(n) => n.as_str().to_string(),
                purecrate_ir::Callee::Method { ty, name } => {
                    format!("{}.{}", ty.as_str(), name.as_str())
                }
                purecrate_ir::Callee::Variant { ty, variant } => {
                    format!("{}.{}", ty.as_str(), variant.as_str())
                }
                purecrate_ir::Callee::StructNew(n) => format!("{}.of", n.as_str()),
                purecrate_ir::Callee::ResultOk => "Result.ok".into(),
                purecrate_ir::Callee::ResultErr => "Result.err".into(),
                purecrate_ir::Callee::OptionSome => String::new(),
                purecrate_ir::Callee::OptionNone => "null".into(),
                purecrate_ir::Callee::Int { ty, op } => {
                    format!("Int.{}.{}", ty.as_str(), op.as_str())
                }
                purecrate_ir::Callee::Fround => "Math.fround".into(),
            };
            if matches!(callee, purecrate_ir::Callee::OptionNone) {
                return "null".into();
            }
            if matches!(callee, purecrate_ir::Callee::OptionSome) {
                return emit_expr(&args[0], indent);
            }
            let a = args
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{c}({a})")
        }
        Expr::Tuple(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Expr::Array(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, indent))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Expr::Return(e) => format!("(() => {{ return {}; }})()", emit_expr(e, indent)),
        Expr::Unreachable => "assertNever(undefined as never)".into(),
    }
}

/// The IR has no parentheses, so a nested operator is always grouped.
fn operand(expr: &Expr, indent: usize) -> String {
    let s = emit_expr(expr, indent);
    match expr {
        Expr::Binary { .. } => format!("({s})"),
        _ => s,
    }
}

/// `{ ...base, a: e1 }`. `?` in the fields and the base is hoisted before this
/// expression, fields first, so the spread running first in JS does not move
/// a failing `?` ahead of an earlier one.
fn emit_struct_update(fields: &Fields, base: &Expr) -> String {
    let Fields::Named(pairs) = fields else {
        unreachable!("struct update has named fields");
    };
    let mut parts = vec![format!("...{}", emit_expr(base, 0))];
    for (name, expr) in pairs {
        parts.push(format!("{}: {}", name.as_str(), emit_expr(expr, 0)));
    }
    format!("({{ {} }})", parts.join(", "))
}

fn emit_struct_value(fields: &Fields) -> String {
    match fields {
        Fields::Unit => "{}".into(),
        Fields::Positional(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, 0))
                .collect::<Vec<_>>()
                .join(", ");
            format!("[{inner}]")
        }
        Fields::Named(pairs) => {
            let inner = pairs
                .iter()
                .map(|(n, e)| format!("{k}: {v}", k = n.as_str(), v = emit_expr(e, 0)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ {inner} }}")
        }
    }
}

fn emit_variant_value(_ty: &str, variant: &str, fields: &Fields) -> String {
    match fields {
        Fields::Unit => format!("{{ kind: \"{variant}\" }}"),
        Fields::Positional(elems) => {
            let inner = elems
                .iter()
                .map(|e| emit_expr(e, 0))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ kind: \"{variant}\", content: [{inner}] }}")
        }
        Fields::Named(pairs) => {
            let inner = pairs
                .iter()
                .map(|(n, e)| format!("{k}: {v}", k = n.as_str(), v = emit_expr(e, 0)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ kind: \"{variant}\", {inner} }}")
        }
    }
}

fn emit_iife(expr: &Expr, indent: usize) -> String {
    let mut body = String::new();
    emit_stmts(expr, indent + 1, Sink::Return, &mut body);
    format!("(() => {{\n{body}{pad}}})()", pad = "  ".repeat(indent))
}

fn bind_prelude(bind: &VariantBind, subject: &str, pad: &str) -> String {
    match bind {
        VariantBind::Unit => String::new(),
        VariantBind::Tuple(pats) => pats
            .iter()
            .enumerate()
            .filter_map(|(i, p)| match p {
                Pattern::Var(n) => Some(format!(
                    "{pad}const {name} = {subject}.content[{i}];\n",
                    name = n.as_str()
                )),
                _ => None,
            })
            .collect(),
        VariantBind::Struct(pairs) => pairs
            .iter()
            .filter_map(|(field, p)| match p {
                Pattern::Var(n) => Some(format!(
                    "{pad}const {name} = {subject}.{f};\n",
                    name = n.as_str(),
                    f = field.as_str()
                )),
                _ => None,
            })
            .collect(),
    }
}

fn emit_lit(lit: &Lit) -> String {
    match lit {
        Lit::Bool(b) => if *b { "true" } else { "false" }.into(),
        Lit::Int { value, ty } => match ty {
            Some(t) if t.is_big() => format!("{value}n"),
            _ => value.to_string(),
        },
        Lit::Float { digits, ty } => match ty {
            Some(FloatTy::F32) => format!("Math.fround({digits})"),
            _ => digits.clone(),
        },
        Lit::Str(s) => format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")),
        Lit::Unit => "undefined".into(),
        Lit::Null => "null".into(),
    }
}

fn bin_op(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Rem => "%",
        BinOp::Eq => "===",
        BinOp::Ne => "!==",
        BinOp::Lt => "<",
        BinOp::Le => "<=",
        BinOp::Gt => ">",
        BinOp::Ge => ">=",
        BinOp::And => "&&",
        BinOp::Or => "||",
    }
}

/// Names one file refers to. A value import also brings the same-named type.
#[derive(Default)]
struct Refs {
    never: bool,
    int: bool,
    result: bool,
    types: BTreeSet<String>,
    values: BTreeSet<String>,
}

impl Refs {
    fn ty(&mut self, ty: &Ty) {
        match ty {
            Ty::Named(n) => {
                self.types.insert(n.as_str().to_string());
            }
            Ty::Result { ok, err } => {
                self.result = true;
                self.ty(ok);
                self.ty(err);
            }
            Ty::Option(inner) | Ty::Vec(inner) => self.ty(inner),
            Ty::Tuple(elems) => elems.iter().for_each(|t| self.ty(t)),
            Ty::Fn { params, ret } => {
                params.iter().for_each(|t| self.ty(t));
                self.ty(ret);
            }
            Ty::Prim(_) | Ty::Never => {}
        }
    }

    fn expr(&mut self, krate: &Crate, expr: &Expr) {
        match expr {
            Expr::Match { scrutinee, arms } => {
                self.never |= arms
                    .iter()
                    .any(|a| matches!(a.pattern, Pattern::Variant { .. }));
                if !is_place(scrutinee) {
                    if let Some(ty) = scrutinee_ty(arms) {
                        self.types.insert(ty.as_str().to_string());
                    }
                }
                self.expr(krate, scrutinee);
                arms.iter().for_each(|a| self.expr(krate, &a.body));
            }
            Expr::Unreachable => self.never = true,
            Expr::Call { callee, args } => {
                match callee {
                    Callee::Fn(n) if is_free_fn(krate, n.as_str()) => {
                        self.values.insert(n.as_str().to_string());
                    }
                    Callee::Method { ty, .. } | Callee::Variant { ty, .. } | Callee::StructNew(ty) => {
                        self.values.insert(ty.as_str().to_string());
                    }
                    Callee::ResultOk | Callee::ResultErr => self.result = true,
                    Callee::Int { .. } => self.int = true,
                    _ => {}
                }
                args.iter().for_each(|a| self.expr(krate, a));
            }
            Expr::Let { ty, value, then, .. } => {
                if let Some(t) = ty {
                    self.ty(t);
                }
                self.expr(krate, value);
                self.expr(krate, then);
            }
            Expr::If { cond, then, else_ } => {
                self.expr(krate, cond);
                self.expr(krate, then);
                self.expr(krate, else_);
            }
            Expr::Construct { fields, base, .. } => {
                match fields {
                    Fields::Positional(xs) => xs.iter().for_each(|e| self.expr(krate, e)),
                    Fields::Named(xs) => xs.iter().for_each(|(_, e)| self.expr(krate, e)),
                    Fields::Unit => {}
                }
                if let Some(b) = base {
                    self.expr(krate, b);
                }
            }
            Expr::Field { base, .. }
            | Expr::Unary { expr: base, .. }
            | Expr::Return(base)
            | Expr::Assign { value: base, .. }
            | Expr::Try { expr: base, .. } => {
                self.expr(krate, base)
            }
            Expr::Binary { left, right, .. } | Expr::Seq { first: left, then: right } => {
                self.expr(krate, left);
                self.expr(krate, right);
            }
            Expr::Tuple(xs) | Expr::Array(xs) => xs.iter().for_each(|e| self.expr(krate, e)),
            Expr::MethodCall { .. } => expr.children().into_iter().for_each(|e| self.expr(krate, e)),
            Expr::Closure { params, ret, body } => {
                params.iter().filter_map(|p| p.ty.as_ref()).for_each(|t| self.ty(t));
                if let Some(t) = ret {
                    self.ty(t);
                }
                self.expr(krate, body);
            }
            Expr::Lit(_) | Expr::Var(_) => {}
        }
    }

    fn fn_sig_and_body(&mut self, krate: &Crate, f: &Fn) {
        f.params.iter().for_each(|p| self.ty(&p.ty));
        self.ty(&f.ret);
        self.expr(krate, &f.body);
    }
}

fn is_free_fn(krate: &Crate, name: &str) -> bool {
    krate
        .items
        .iter()
        .any(|item| matches!(item, Item::Fn(f) if f.owner.is_none() && f.name.as_str() == name))
}

fn imports_for(krate: &Crate, stem: &str, items: &[&Item]) -> String {
    let mut refs = Refs::default();
    for item in items {
        match item {
            Item::Struct(st) => {
                st.fields.iter().for_each(|f| refs.ty(&f.ty));
                methods_on(krate, st.name.as_str())
                    .into_iter()
                    .for_each(|m| refs.fn_sig_and_body(krate, m));
            }
            Item::Enum(en) => {
                for v in &en.variants {
                    match &v.fields {
                        VariantFields::Unit => {}
                        VariantFields::Tuple(tys) => tys.iter().for_each(|t| refs.ty(t)),
                        VariantFields::Struct(fs) => fs.iter().for_each(|f| refs.ty(&f.ty)),
                    }
                }
                methods_on(krate, en.name.as_str())
                    .into_iter()
                    .for_each(|m| refs.fn_sig_and_body(krate, m));
            }
            Item::Alias(al) => refs.ty(&al.ty),
            Item::Fn(f) if f.owner.is_none() => refs.fn_sig_and_body(krate, f),
            Item::Fn(_) => {}
        }
    }

    let elsewhere = |name: &String| Name::new(name.clone()).file_stem() != stem;
    let mut out = String::new();
    if refs.never {
        out.push_str("import { assertNever } from \"./assert-never.ts\";\n");
    }
    if refs.int {
        out.push_str("import { Int } from \"./int.ts\";\n");
    }
    if refs.result {
        out.push_str("import { Result } from \"./result.ts\";\n");
    }
    for v in refs.values.iter().filter(|v| elsewhere(v)) {
        out.push_str(&format!(
            "import {{ {v} }} from \"./{s}.ts\";\n",
            s = Name::new(v.clone()).file_stem()
        ));
    }
    for t in refs
        .types
        .iter()
        .filter(|t| elsewhere(t) && !refs.values.contains(*t))
    {
        out.push_str(&format!(
            "import type {{ {t} }} from \"./{s}.ts\";\n",
            s = Name::new(t.clone()).file_stem()
        ));
    }
    out
}

