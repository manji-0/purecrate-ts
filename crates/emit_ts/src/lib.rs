    #[test]
    fn object_literals_behind_a_comment_are_parenthesized() {
        use purecrate_ir::Wrapper;
        let lit = Expr::Construct {
            ty: Name::new("P"),
            variant: None,
            fields: Fields::Named(vec![(Name::new("a"), Expr::var("a"))]),
            base: None,
        };
        let boxed = Expr::Ignored {
            wrapper: Wrapper::Box,
            expr: Box::new(lit.clone()),
        };
        let body = arrow_expr(&boxed, 0);
        assert!(body.starts_with("(/* ") && body.ends_with("{ a: a })"), "{body}");
        let mut out = String::new();
        Sink::Effect.finish_expr(&boxed, 0, &mut out);
        assert!(out.starts_with("(/* ") && out.ends_with("{ a: a });\n"), "{out}");
        let some = Expr::Call {
            callee: Callee::OptionSome,
            args: vec![lit],
        };
        assert_eq!(arrow_expr(&some, 0), "({ a: a })");
    }

