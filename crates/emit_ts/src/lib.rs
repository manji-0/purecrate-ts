/// First line of every generated `.ts` file. `build` also reads it to tell
/// its own output from a directory it must not replace.
pub const HEADER: &str = "/* generated by purecrate-ts. do not edit. */\n";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct File {
    pub stem: String,
    pub source: String,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Package {
    pub files: Vec<File>,
}

pub fn emit(krate: &Crate) -> Package {
    let structs = krate.items.iter().filter_map(|item| match item {
        Item::Struct(st) => Some(st.name.as_str().to_string()),
        _ => None,
    });
    let enums = krate.items.iter().filter_map(|item| match item {
        Item::Enum(e) => Some((e.name.as_str().to_string(), e.variants.iter().map(|v| v.name.clone()).collect())),
        _ => None,
    });
    scoped(&CLOSED_FIELDS, closed_fields(krate), || {
        scoped(&PRIVATE, private_methods(krate), || {
            scoped(&STRUCTS, structs.collect(), || {
                scoped(&ENUMS, enums.collect(), || {
                    scoped(&STRINGY, stringy_names(krate), || {
                        scoped(&HOSTED, krate.homes(|item| krate.fns_named(item)), || {
                            with_internal_names(krate, || emit_package(krate))
                        })
                    })
                })
            })
        })
    })
}

/// The file a helper is printed in, when not its own (`homes`).
pub(crate) fn hosted_in(name: &str) -> Option<String> {
    HOSTED.with(|h| h.borrow().get(name).cloned())
}

fn emit_package(krate: &Crate) -> Package {
    let mut buckets: BTreeMap<String, Vec<&Item>> = BTreeMap::new();
    for item in &krate.items {
        buckets.entry(HOSTED.with(|h| Crate::home(item, &h.borrow()))).or_default().push(item);
    }

    let mut files = Vec::new();

    for (stem, items) in &buckets {
        files.push(File { stem: stem.clone(), source: emit_file(krate, stem, items) });
    }

    files.push(File { stem: "index".to_string(), source: emit_index(krate) });

    Package { files }
}

fn emit_file(krate: &Crate, stem: &str, items: &[&Item]) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    let imports = imports_for(krate, stem, items);
    out.push_str(&imports);
    if !imports.is_empty() {
        out.push('\n');
    }
    TABLES.with(|t| t.borrow_mut().clear());
    let mut body = String::new();
    let out_ = &mut body;
    let mut previous: Option<&Item> = None;
    for item in items {
        // A blank line between declarations; a run of consts stays together.
        // A method or an associated const prints in its owner's companion.
        let printed = item.owner().is_none();
        if printed {
            // A const with a `//` above it opens a paragraph of its own.
            let commented = matches!(item, Item::Const(c) if !c.comment.is_empty());
            if previous.is_some_and(|p| commented || !(matches!(p, Item::Const(_)) && matches!(item, Item::Const(_)))) {
                out_.push('\n');
            }
            previous = Some(item);
        }
        match item {
            Item::Enum(en) => out_.push_str(&emit_enum(krate, en)),
            Item::Struct(st) => out_.push_str(&emit_struct(krate, st)),
            Item::Alias(al) => {
                out_.push_str(&jsdoc(&al.doc, ""));
                out_.push_str(&format!("export type {name} = {ty};\n", name = al.name.as_str(), ty = emit_ty(&al.ty)));
            }
            // A hosted helper is the file's own; nothing else imports it.
            Item::Fn(f) if f.owner.is_none() && hosted_in(f.name.as_str()).is_some() => {
                out_.push_str(&emit_free_fn(f).replacen("export const ", "const ", 1))
            }
            Item::Fn(f) if f.owner.is_none() => out_.push_str(&emit_free_fn(f)),
            Item::Fn(_) => {}
            Item::Const(c) if c.owner.is_some() => {}
            Item::Const(c) => {
                c.comment
                    .iter()
                    .for_each(|l| out_.push_str(&if l.is_empty() { "//\n".to_string() } else { format!("// {l}\n") }));
                out_.push_str(&jsdoc(&c.doc, ""));
                out_.push_str(&const_decl(c.name.as_str(), c));
            }
        }
    }
    for (_, _, decl) in TABLES.with(|t| std::mem::take(&mut *t.borrow_mut())) {
        out.push_str(&decl);
        out.push('\n');
    }
    out.push_str(&body);
    // A companion with nothing in it is `{}`, as oxfmt prints it.
    let out = out.replace(" = {\n} as const;", " = {} as const;");
    paragraph::paragraphs(&destructure::destructure(&plain::plain_names(&imports::prune_unused(&out))))
}

